const dicts: Record<Lang, Record<TKey, string>> = { en, ar };

export type T = (key: TKey | string, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => {
    let s: string = dicts[lang][key as TKey] ?? dicts.en[key as TKey] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export const LangContext = createContext<{ lang: Lang; t: T }>({ lang: 'ar', t: makeT('ar') });
export const useT = () => useContext(LangContext);
